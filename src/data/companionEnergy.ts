/** 根据能量值获取状态 */
export function getCompanionState(energy: number): CompanionStateMeta {
  if (energy <= 0) return COMPANION_STATES.find(s => s.state === "sleeping")!;
  return COMPANION_STATES.find(s => energy >= s.range[0] && energy <= s.range[1])!
    ?? COMPANION_STATES[0];
}

// ---- 衰减规则 ----

/** 每小时衰减点数 */
export const DECAY_PER_HOUR = 4;
/** 每日自然衰减上限（防太肝，也避免免费玩家被逼氪） */
export const DECAY_PER_DAY_CAP = 30;
/** 月卡用户每日自动恢复点数 */
export const VIP_DAILY_RECOVERY = 30;
/** 每日登录赠送能量（免费玩家活路） */
export const LOGIN_DAILY_BONUS = 20;

/**
 * 计算从上次更新时间到现在的自然衰减值。
 * @param lastUpdatedAt 上次能量更新的时间戳（毫秒）
 * @param now 当前时间戳（默认 Date.now()）
 * @returns 应衰减的能量点数（非负）
 */
export function calcDecay(lastUpdatedAt: number, now: number = Date.now()): number {
  if (lastUpdatedAt <= 0) return 0;
  const elapsedMs = now - lastUpdatedAt;
  if (elapsedMs <= 0) return 0;
  const elapsedHours = elapsedMs / (1000 * 60 * 60);
  const elapsedDays = elapsedMs / (1000 * 60 * 60 * 24);

  // [BUG-FIX] 原实现用 Math.min(rawDecay, Math.floor(elapsedDays*CAP)) 会把短时间离线
  // 错误压制（如离线 1 小时 cappedDecay=floor(1/24*30)=1，反而比真实 4 点还低）。
  // 正确逻辑：完整天数部分每天封顶 30 点；不足一天部分按 4/小时计算（且当天最多 30 点）。
  const fullDays = Math.floor(elapsedDays);
  const partialHours = elapsedHours - fullDays * 24;
  const fullDaysDecay = fullDays * DECAY_PER_DAY_CAP;
  const partialDecay = Math.min(Math.floor(partialHours * DECAY_PER_HOUR), DECAY_PER_DAY_CAP);
  return fullDaysDecay + partialDecay;
}

/**
 * 计算当前能量值（应用衰减）。
 */
export function calcCurrentEnergy(energy: number, lastUpdatedAt: number, now = Date.now()): number {
  return Math.max(0, energy - calcDecay(lastUpdatedAt, now));
}

