/** 从某个话术列表随机取一条（避免连续重复） */
export function pickPhrase(list: string[], lastIndexRef?: { current: number }): string {
  if (!list.length) return "";
  if (list.length === 1) return list[0];
  let idx = Math.floor(Math.random() * list.length);
  if (lastIndexRef) {
    // 避免与上一次相同
    let guard = 0;
    while (idx === lastIndexRef.current && guard < 5) {
      idx = Math.floor(Math.random() * list.length);
      guard++;
    }
    lastIndexRef.current = idx;
  }
  return list[idx];
}

/** 根据状态获取对应话术列表 */
export function getPhrasesForState(state: CompanionState): string[] {
  switch (state) {
    case "warm": return PHRASES.warm;
    case "hurt": return PHRASES.hurt;
    case "distant": return PHRASES.distant;
    case "farewell": return PHRASES.farewell;
    case "sleeping": return [];
    default: return PHRASES.warm;
  }
}
